export function assessReadiness(answers) {
  if(!Array.isArray(answers)||answers.length!==QUESTIONS.length) return null;
  let score=0;
  for(let i=0;i<QUESTIONS.length;i++) {
    const choice=answers[i];
    if(!Number.isInteger(choice)||!QUESTIONS[i].options[choice]) return null;
    score+=QUESTIONS[i].options[choice][1];
  }
  return {score,tier:score<=11?'prepare':score<=19?'pilot':'ready',unlocked:score>=12};
}
